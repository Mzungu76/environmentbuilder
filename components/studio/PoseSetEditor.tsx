'use client';

import { useEffect, useRef, useState } from 'react';
import type { Puppet, PoseSet } from '@/types';
import { drawPuppet } from '@/engine/puppet/canvasRenderer';
import { frameQualities, sampleSet } from '@/engine/puppet/keyposes';
import { skinVertices } from '@/engine/puppet/runtime';
import { ACCEPTED_IMAGE_TYPES } from '@/lib/import-export/image';
import { imgToCanvas, loadAssetImg, pruneAssets, updatePuppet } from '@/lib/studio/pipeline';
import { importPoseSheet } from '@/lib/studio/poseSets';
import { ed } from './shared';

type Store = import('@/lib/store/editorStore').EditorStore;

/**
 * Climb as a SEQUENCE of key poses (recommended): one sheet with N poses side by side (generated by the AI with the prompt in the
 * guide). The app cuts the figures out, proposes a skeleton for each, equalises the scale and plays them key → key with the
 * skeleton difference warping the neighbours into the in-between pose.
 */
export function PoseSetEditor({ store, puppet, projectId }: { store: Store; puppet: Puppet; projectId: string }) {
  const file = useRef<HTMLInputElement>(null);
  const [count, setCount] = useState(4);
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState<string | null>(null);
  const set = puppet.poseSets?.climb;

  const setSet = (fn: (s: PoseSet) => PoseSet | null) => updatePuppet(store, puppet.id, (p) => {
    const cur = p.poseSets?.climb; if (!cur) return p;
    const next = fn(cur); const ps = { ...(p.poseSets ?? {}) };
    if (next) ps.climb = next; else delete ps.climb;
    return { ...p, poseSets: ps };
  });

  const load = async (f: File) => {
    setBusy(true); setMsg(null);
    try {
      const r = await importPoseSheet(store, puppet, f, count);
      updatePuppet(store, puppet.id, (p) => ({ ...p, assets: [...p.assets, ...r.metas, r.sourceMeta], poseSets: { ...(p.poseSets ?? {}), climb: { frames: r.frames, duration: set?.duration ?? 1.2, loop: set?.loop ?? true } } }));
      await pruneAssets(store, puppet.id);
      setMsg(`Sequenza creata: ${r.frames.length} pose. Controlla l’anteprima e gli avvisi sotto le miniature.`);
    } catch (e) { setMsg(`Errore: ${e instanceof Error ? e.message : e}`); }
    setBusy(false);
  };

  const q = set ? frameQualities(set.frames) : [];
  const move = (i: number, d: number) => setSet((s) => { const fr = [...s.frames], j = i + d; if (j < 0 || j >= fr.length) return s; [fr[i], fr[j]] = [fr[j], fr[i]]; return { ...s, frames: fr }; });
  const remove = (i: number) => { setSet((s) => (s.frames.length <= 1 ? null : { ...s, frames: s.frames.filter((_, k) => k !== i) })); void pruneAssets(store, puppet.id); };

  return (
    <div style={{ display: 'grid', gap: 6 }} data-testid="poseset">
      <h4 style={{ margin: 0 }}>Sequenza di pose — arrampicata (consigliata)</h4>
      <span className={ed.help}>Un unico foglio con le pose dell’arrampicata una accanto all’altra, nell’ordine del movimento (es. 4: mano destra su, mano sinistra su, piede destro su, piede sinistro su). Il programma ritaglia, mette lo scheletro, uniforma la scala e anima da una posa all’altra: risultato molto più fedele di una sola immagine deformata. Il prompt per l’AI è nella guida (passo 1).</span>
      <div className={ed.row2} style={{ gridTemplateColumns: 'auto 1fr' }}>
        <label className={ed.help} style={{ alignSelf: 'center' }}>Pose nel foglio</label>
        <input type="number" min={2} max={8} value={count} onChange={(e) => setCount(Math.min(8, Math.max(2, Number(e.target.value) || 4)))} aria-label="Numero di pose nel foglio" data-testid="set-count" />
      </div>
      <button className={ed.btn} disabled={busy} onClick={() => file.current?.click()} data-testid="set-import">{set ? 'Sostituisci la sequenza…' : 'Importa foglio pose arrampicata…'}</button>
      {busy && <span className={ed.help}>Elaborazione…</span>}
      {msg && <span className={ed.help} style={{ color: 'var(--text)' }} role="status" data-testid="set-msg">{msg}</span>}
      <input ref={file} type="file" accept={ACCEPTED_IMAGE_TYPES.join(',')} hidden data-testid="set-file" onChange={(e) => { const f = e.target.files?.[0]; e.target.value = ''; if (f) void load(f); }} />
      {set && (
        <>
          <div style={{ display: 'flex', gap: 6, overflowX: 'auto', paddingBottom: 4 }} data-testid="set-frames">
            {set.frames.map((fr, i) => (
              <div key={fr.cutoutAssetId ?? i} style={{ minWidth: 112, display: 'grid', gap: 2, justifyItems: 'center', border: `1px solid ${q[i]?.ok ? 'var(--border)' : '#e0a030'}`, borderRadius: 6, padding: 4 }}>
                <Thumb projectId={projectId} assetId={fr.cutoutAssetId} />
                <span className={ed.help}>{i + 1}{q[i]?.ok ? ' ✓' : ' ⚠'}</span>
                <span style={{ display: 'flex', gap: 2, flexWrap: 'nowrap' }}>
                  <button className={ed.btn} style={{ padding: '2px 8px', minWidth: 0 }} onClick={() => move(i, -1)} disabled={i === 0} aria-label={`Sposta la posa ${i + 1} a sinistra`}>◀</button>
                  <button className={ed.btn} style={{ padding: '2px 8px', minWidth: 0 }} onClick={() => move(i, 1)} disabled={i === set.frames.length - 1} aria-label={`Sposta la posa ${i + 1} a destra`}>▶</button>
                  <button className={`${ed.btn} ${ed.btnDanger}`} style={{ padding: '2px 8px', minWidth: 0 }} onClick={() => remove(i)} aria-label={`Rimuovi la posa ${i + 1}`}>✕</button>
                </span>
              </div>
            ))}
          </div>
          {q.some((x) => !x.ok) && (
            <ul className={ed.help} style={{ margin: 0, paddingLeft: 18, color: '#e0a030' }} data-testid="set-warn">
              {q.map((x, i) => x.ok ? null : <li key={i}>Posa {i + 1}: {x.issues.join('; ')}.</li>)}
            </ul>
          )}
          <SetPreview set={set} projectId={projectId} />
          <label className={ed.help}>Durata del ciclo: {set.duration.toFixed(1)} s</label>
          <input type="range" min={0.4} max={4} step={0.1} value={set.duration} onChange={(e) => setSet((s) => ({ ...s, duration: Number(e.target.value) }))} aria-label="Durata del ciclo" />
          <label className={ed.help}><input type="checkbox" checked={set.loop} onChange={(e) => setSet((s) => ({ ...s, loop: e.target.checked }))} /> Ripeti in ciclo (l’ultima posa torna alla prima)</label>
          <button className={`${ed.btn} ${ed.btnDanger}`} onClick={() => { setSet(() => null); void pruneAssets(store, puppet.id); }}>Elimina la sequenza</button>
        </>
      )}
    </div>
  );
}

function Thumb({ projectId, assetId }: { projectId: string; assetId: string | null }) {
  const ref = useRef<HTMLCanvasElement>(null);
  useEffect(() => {
    let alive = true;
    if (!assetId) return;
    loadAssetImg(projectId, assetId).then((img) => {
      const c = ref.current; if (!alive || !img || !c) return;
      const s = Math.min(76 / img.width, 76 / img.height); c.width = Math.max(1, Math.round(img.width * s)); c.height = Math.max(1, Math.round(img.height * s));
      c.getContext('2d')!.drawImage(imgToCanvas(img), 0, 0, c.width, c.height);
    });
    return () => { alive = false; };
  }, [projectId, assetId]);
  return <canvas ref={ref} width={76} height={76} style={{ width: 76, height: 76, objectFit: 'contain' }} aria-hidden />;
}

/** Animated preview: the same sampling the game uses (sampleSet + skinVertices), Canvas2D layers. */
function SetPreview({ set, projectId }: { set: PoseSet; projectId: string }) {
  const cv = useRef<HTMLCanvasElement>(null);
  const [paused, setPaused] = useState(false);
  const imgs = useRef(new Map<string, HTMLCanvasElement>());
  const live = useRef({ set, paused, phase: 0 });
  live.current.set = set; live.current.paused = paused;

  useEffect(() => {
    let alive = true;
    for (const f of set.frames) if (f.cutoutAssetId && !imgs.current.has(f.cutoutAssetId)) { const id = f.cutoutAssetId; void loadAssetImg(projectId, id).then((i) => { if (i && alive) imgs.current.set(id, imgToCanvas(i)); }); }
    return () => { alive = false; };
  }, [set.frames, projectId]);

  useEffect(() => {
    let raf = 0, last = performance.now();
    const tick = (now: number) => {
      const L = live.current, c = cv.current;
      const dt = Math.min(0.1, (now - last) / 1000); last = now;
      if (!L.paused) L.phase = L.set.loop ? (L.phase + dt / L.set.duration) % 1 : Math.min(1, L.phase + dt / L.set.duration);
      if (c) {
        const ctx = c.getContext('2d')!; ctx.clearRect(0, 0, c.width, c.height);
        const s = sampleSet(L.set, L.phase);
        if (s) {
          for (const layer of [s.under, s.over]) {
            if (!layer) continue;
            const im = layer.view.cutoutAssetId ? imgs.current.get(layer.view.cutoutAssetId) : undefined, pos = skinVertices(layer.view, layer.pose);
            if (!im || !pos || !layer.view.mesh) continue;
            ctx.save(); ctx.globalAlpha = layer.alpha;
            drawPuppet(ctx, im, pos, layer.view.mesh.uvs, layer.view.mesh.indices, { x: c.width / 2, y: c.height * 0.92, scale: (c.height * 0.62) / layer.view.figureHeight, flip: false, pivot: layer.view.pivot });
            ctx.restore();
          }
        }
      }
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, []);

  return (
    <div style={{ display: 'grid', gap: 4 }}>
      <canvas ref={cv} width={300} height={320} style={{ width: '100%', maxWidth: 300, background: '#10131a', borderRadius: 8 }} data-testid="set-preview" aria-label="Anteprima della sequenza" />
      <button className={ed.btn} onClick={() => setPaused((p) => !p)} data-testid="set-pause">{paused ? 'Riproduci' : 'Ferma'}</button>
    </div>
  );
}
