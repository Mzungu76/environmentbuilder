// Builds dist/environment-runtime.mjs: the dependency-free runtime for host games (ES module).
import { build } from 'esbuild';
import path from 'node:path';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const root = path.resolve(import.meta.dirname, '..');
await build({
  entryPoints: [path.join(root, 'engine/public.ts')], bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true,
  outfile: path.join(root, 'dist/environment-runtime.mjs'), alias: { '@': root }, logLevel: 'warning',
});
// Also embedded in the app (puppet packages ship the runtime so a host game needs no build step).
const src = readFileSync(path.join(root, 'dist/environment-runtime.mjs'), 'utf8');
mkdirSync(path.join(root, 'lib/generated'), { recursive: true });
writeFileSync(path.join(root, 'lib/generated/runtimeSource.ts'), `// GENERATED by tools/build-runtime.mjs — do not edit.\nexport const RUNTIME_SOURCE = ${JSON.stringify(src)};\n`);
console.log('dist/environment-runtime.mjs', src.length, 'bytes');
